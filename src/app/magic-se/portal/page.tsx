function PlacedNodeView({
  node, selected, onDrag, onStartConnect, onEndConnect, connecting, highlightedPorts,
  onContextMenu, onPortEnter, onPortLeave, onMouseDownSelect,
  onInlineChange, connections, onPortAltClick, simHighlight, onDoubleClick,
  onRename, renameRequestId, onBodyMouseUp, locked,
}: {
  node: PlacedNode; selected: boolean;
  onDrag: (id: string, dx: number, dy: number) => void;
  onStartConnect: (instanceId: string, side: 'in' | 'out', portIndex: number, e: React.MouseEvent) => void;
  onEndConnect: (instanceId: string, side: 'in' | 'out', portIndex: number, e: React.MouseEvent) => void;
  connecting: boolean; highlightedPorts: Set<string>;
  onContextMenu: (e: React.MouseEvent, instanceId: string) => void;
  onPortEnter: (instanceId: string, side: 'in' | 'out', portIndex: number) => void;
  onPortLeave: () => void;
  onMouseDownSelect: (e: React.MouseEvent, instanceId: string) => void;
  onInlineChange: (instanceId: string, portIndex: number, value: string) => void;
  connections: Connection[];
  onPortAltClick: (instanceId: string, side: 'in' | 'out', portIndex: number) => void;
  simHighlight?: boolean;
  onDoubleClick?: (instanceId: string) => void;
  onRename?: (instanceId: string, newTitle: string) => void;
  renameRequestId?: string | null;
  onBodyMouseUp?: (instanceId: string, e: React.MouseEvent) => void;
  locked?: boolean;
}) {
  const [hoverTarget, setHoverTarget] = useState<'node' | 'port' | null>(null);
  const [dragging, setDragging] = useState(false);
  const [editingTitle, setEditingTitle] = useState(false);
  const [titleDraft, setTitleDraft] = useState(node.title);
  const dragStart = useRef({ x: 0, y: 0 });

  // ★ 仅按 prop 判定锁定；虚拟节点默认不锁，可自由拖动
  const isLocked = !!locked;

  useEffect(() => {
    if (renameRequestId === node.instanceId) {
      setEditingTitle(true);
      setTitleDraft(node.title);
    }
  }, [renameRequestId, node.instanceId, node.title]);

  useEffect(() => {
    if (!editingTitle) setTitleDraft(node.title);
  }, [node.title, editingTitle]);

  const commitTitle = () => {
    setEditingTitle(false);
    const t = titleDraft.trim();
    if (t && t !== node.title) onRename?.(node.instanceId, t);
  };

  const onMouseDown = (e: React.MouseEvent) => {
    e.stopPropagation();
    onMouseDownSelect(e, node.instanceId);
    if (isLocked) return;
    setDragging(true);
    dragStart.current = { x: e.clientX, y: e.clientY };
  };
  const onMouseMove = (e: React.MouseEvent) => {
    if (isLocked) return;
    if (!dragging) return;
    const dx = e.clientX - dragStart.current.x;
    const dy = e.clientY - dragStart.current.y;
    dragStart.current = { x: e.clientX, y: e.clientY };
    onDrag(node.instanceId, dx, dy);
  };
  const onMouseUp = () => setDragging(false);

  const typeTag = (() => {
    if (node.category === '事件') return 'EVENT';
    if (node.category === '变量') return node.id.startsWith('var_get') ? 'GET' : 'SET';
    if (node.category === '宏节点') return 'MACRO';
    if (node.category === '函数') return 'FUNC';
    if (node.category === '定义入口' || node.category === '定义出口') return 'FUNC';
    const hasExecOut = node.outputs.some((p) => p.type === 'exec');
    if (!hasExecOut) return 'PURE';
    return 'FUNC';
  })();

  return (
    <div className="absolute select-none" data-node
      style={{ left: node.x, top: node.y, width: NODE_WIDTH }}
      onMouseMove={onMouseMove}
      onMouseUp={(e) => { onMouseUp(); onBodyMouseUp?.(node.instanceId, e); }}
      onMouseLeave={() => { setDragging(false); setHoverTarget(null); }}
      onContextMenu={(e) => onContextMenu(e, node.instanceId)}
      onDoubleClick={(e) => { e.stopPropagation(); onDoubleClick?.(node.instanceId); }}>
      <div className="overflow-hidden border backdrop-blur-md transition-shadow"
        style={{
          borderRadius: 2,
          borderColor: selected ? GOLD : hoverTarget === 'node' ? 'rgba(200,169,106,0.6)' : 'rgba(232,230,226,0.08)',
          background: 'rgba(21,21,23,0.85)',
          boxShadow: simHighlight
            ? `0 0 0 1.5px ${GOLD}, 0 0 20px ${GOLD_SOFT}, 0 6px 24px rgba(0,0,0,0.55)`
            : selected
            ? `0 0 0 1px ${GOLD_SOFT}, 0 6px 24px rgba(0,0,0,0.55)`
            : '0 4px 20px rgba(0,0,0,0.45)',
        }}
        onMouseEnter={() => setHoverTarget('node')}
        onMouseLeave={(e) => {
          const related = e.relatedTarget as HTMLElement | null;
          if (related?.closest('[data-port]')) return;
          setHoverTarget(null);
        }}>
        <div onMouseDown={onMouseDown}
          className={`border-b px-3 py-2 ${isLocked ? 'cursor-default' : 'cursor-grab active:cursor-grabbing'}`}
          style={{ background: `linear-gradient(180deg, ${node.color}dd, ${node.color}aa)`, height: HEADER_H, borderColor: 'rgba(0,0,0,0.35)' }}>
          <div className="flex items-start justify-between gap-2">
            {editingTitle && !isLocked ? (
              <input autoFocus value={titleDraft}
                onChange={(e) => setTitleDraft(e.target.value)}
                onBlur={commitTitle}
                onKeyDown={(e) => {
                  if (e.key === 'Enter') commitTitle();
                  if (e.key === 'Escape') { setEditingTitle(false); setTitleDraft(node.title); }
                }}
                onMouseDown={(e) => e.stopPropagation()}
                className="w-full border-b border-dashed bg-transparent text-xs text-white focus:outline-none"
                style={{ borderColor: 'rgba(255,255,255,0.5)' }} />
            ) : (
              <p className="truncate select-none text-xs font-normal text-white"
                onDoubleClick={(e) => {
                  if (isLocked) return;
                  e.stopPropagation(); setEditingTitle(true); setTitleDraft(node.title);
                }}>
                {node.title}
              </p>
            )}
            <span className="shrink-0 bg-black/35 px-1 py-0.5 font-mono text-[8px] uppercase text-white/85">{typeTag}</span>
          </div>
          <p className="mt-0.5 text-[10px] text-white/70">{node.category}</p>
        </div>
        <div className="flex justify-between gap-3 px-3 py-2" style={{ minHeight: 40 }}>
          <div className="flex flex-col gap-1.5">
            {node.inputs.map((p, i) => {
              const isConnected = connections.some((c) => c.toInstance === node.instanceId && c.toPort === i);
              return (
                <PortView key={i} port={p} side="in" connecting={connecting}
                  highlight={highlightedPorts.has(`${node.instanceId}:in:${i}`)}
                  onStartDrag={(s, e) => onStartConnect(node.instanceId, s, i, e)}
                  onEndDrag={(s, e) => onEndConnect(node.instanceId, s, i, e)}
                  onHoverChange={(h) => setHoverTarget(h ? 'port' : 'node')}
                  onPortEnter={() => onPortEnter(node.instanceId, 'in', i)} onPortLeave={onPortLeave}
                  inlineValue={node.defaultValues?.[i] ?? ''}
                  inlineConnected={isConnected}
                  onInlineChange={(v) => onInlineChange(node.instanceId, i, v)}
                  onAltClick={() => onPortAltClick(node.instanceId, 'in', i)} />
              );
            })}
          </div>
          <div className="flex flex-col items-end gap-1.5">
            {node.outputs.map((p, i) => {
              const isConnected = connections.some((c) => c.fromInstance === node.instanceId && c.fromPort === i);
              return (
                <PortView key={i} port={p} side="out" connecting={connecting}
                  highlight={highlightedPorts.has(`${node.instanceId}:out:${i}`)}
                  onStartDrag={(s, e) => onStartConnect(node.instanceId, s, i, e)}
                  onEndDrag={(s, e) => onEndConnect(node.instanceId, s, i, e)}
                  onHoverChange={(h) => setHoverTarget(h ? 'port' : 'node')}
                  onPortEnter={() => onPortEnter(node.instanceId, 'out', i)} onPortLeave={onPortLeave}
                  inlineConnected={isConnected}
                  onAltClick={() => onPortAltClick(node.instanceId, 'out', i)} />
              );
            })}
          </div>
        </div>
      </div>
      {hoverTarget === 'node' && (
        <div className="pointer-events-none absolute left-0 top-full z-50 mt-2 w-72 overflow-hidden border p-3 text-left shadow-2xl backdrop-blur-xl"
          style={{ borderRadius: 2, borderColor: 'rgba(232,230,226,0.08)', background: '#1b1b1e' }}>
          <p className="text-xs font-normal text-[#e8e6e2]">{node.title}</p>
          <p className="mt-1 text-[10px] text-[#8b8885]">{node.category}</p>
          <p className="mt-2 text-[10px] leading-5 text-[#9a9792]">{node.desc}</p>
          {node.commonScene && (
            <div className="mt-2 border-t pt-2" style={{ borderColor: 'rgba(232,230,226,0.06)' }}>
              {renderCommonScene(node.commonScene)}
            </div>
          )}
          {node.source && isOfficialSource(node.source) && (
            <a href={node.source} target="_blank" rel="noreferrer"
              className="mt-2 inline-block border-t pt-2 text-[10px] hover:underline"
              style={{ borderColor: 'rgba(232,230,226,0.06)', color: GOLD }}
              onClick={(e) => e.stopPropagation()}>来源自官方文档 ↗</a>
          )}
        </div>
      )}
    </div>
  );
}

