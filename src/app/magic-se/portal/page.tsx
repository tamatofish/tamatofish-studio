/* ==================== 缩略图 ==================== */
function Minimap({ placed, pan, scale, canvasSize, onJump }: {
  placed: PlacedNode[]; pan: { x: number; y: number }; scale: number;
  canvasSize: { w: number; h: number };
  onJump: (worldX: number, worldY: number) => void;
}) {
  const MAP_W = 180, MAP_H = 120;
  const WORLD_W = 3000, WORLD_H = 2000;
  const toMap = (x: number, y: number) => ({ mx: (x / WORLD_W) * MAP_W, my: (y / WORLD_H) * MAP_H });
  const vpWorldX = -pan.x / scale;
  const vpWorldY = -pan.y / scale;
  const vpWorldW = canvasSize.w / scale;
  const vpWorldH = canvasSize.h / scale;
  const vp = toMap(vpWorldX, vpWorldY);
  const vpW = (vpWorldW / WORLD_W) * MAP_W;
  const vpH = (vpWorldH / WORLD_H) * MAP_H;
  return (
    <div className="pointer-events-auto fixed bottom-12 right-4 z-40 overflow-hidden border backdrop-blur-xl"
      style={{ width: MAP_W, height: MAP_H, cursor: 'crosshair', borderRadius: 2, borderColor: 'rgba(232,230,226,0.08)', background: 'rgba(21,21,23,0.85)' }}
      onClick={(e) => {
        const rect = (e.currentTarget as HTMLElement).getBoundingClientRect();
        const mx = e.clientX - rect.left;
        const my = e.clientY - rect.top;
        onJump((mx / MAP_W) * WORLD_W, (my / MAP_H) * WORLD_H);
      }}>
      <div className="pointer-events-none absolute inset-x-0 top-0 h-px"
        style={{ background: `linear-gradient(to right, transparent, ${GOLD_SOFT}, transparent)` }} />
      {placed.map((n) => {
        const { mx, my } = toMap(n.x, n.y);
        return (
          <div key={n.instanceId} className="pointer-events-none absolute"
            style={{
              left: mx, top: my,
              width: Math.max(2, (NODE_WIDTH / WORLD_W) * MAP_W),
              height: Math.max(2, (60 / WORLD_H) * MAP_H),
              background: n.color, opacity: 0.55,
            }} />
        );
      })}
      <div className="pointer-events-none absolute border"
        style={{
          left: vp.mx, top: vp.my,
          width: Math.max(4, vpW), height: Math.max(4, vpH),
          borderColor: GOLD, background: 'rgba(200,169,106,0.1)',
        }} />
    </div>
  );
}

/* ==================== 内联输入框 ==================== */
function InlineInput({ port, value, connected, onChange }: {
  port: Port; value: string; connected: boolean; onChange: (v: string) => void;
}) {
  if (connected) return <span className="ml-1 shrink-0 text-[10px] italic text-[#5b5852]">{value || '已连线'}</span>;
  const isText = port.type === 'string';
  const isBool = port.type === 'bool';
  const isVec = port.type === 'vector';
  const isRot = port.type === 'rotator';
  if (isBool) {
    return (
      <label className="ml-1 flex shrink-0 cursor-pointer items-center gap-1 text-[10px] text-[#c9c7c2]">
        <input type="checkbox" checked={value === 'true'}
          onChange={(e) => onChange(e.target.checked ? 'true' : 'false')}
          className="h-3 w-3 cursor-pointer" style={{ accentColor: GOLD }} />
      </label>
    );
  }
  if (isVec || isRot) {
    const parts = (value || '0,0,0').split(',');
    const labels = isVec ? ['X', 'Y', 'Z'] : ['P', 'Y', 'R'];
    return (
      <div className="ml-1 flex shrink-0 items-center gap-0.5" onClick={(e) => e.stopPropagation()}>
        {labels.map((lbl, i) => (
          <div key={i} className="flex items-center">
            <span className="text-[9px] text-[#5b5852]">{lbl}</span>
            <input type="text" value={parts[i] ?? '0'}
              onChange={(e) => { const next = [...parts]; next[i] = e.target.value; onChange(next.join(',')); }}
              className="w-6 border bg-black/30 px-0.5 py-0.5 text-[10px] text-[#e0e0e0] focus:outline-none"
              style={{ borderRadius: 2, borderColor: 'rgba(232,230,226,0.1)' }} />
          </div>
        ))}
      </div>
    );
  }
  return (
    <input type="text" value={value}
      onChange={(e) => onChange(e.target.value)}
      onClick={(e) => e.stopPropagation()}
      onMouseDown={(e) => e.stopPropagation()}
      placeholder={isText ? '输入文本' : '0'}
      className={`ml-1 shrink-0 border bg-black/30 px-1 py-0.5 text-[10px] text-[#e0e0e0] placeholder:text-[#5b5852] focus:outline-none ${isText ? 'w-20' : 'w-12'}`}
      style={{ borderRadius: 2, borderColor: 'rgba(232,230,226,0.1)' }} />
  );
}

