type CustomVarType = 'float' | 'int' | 'string' | 'bool' | 'vector' | 'rotator';

interface CustomVariable {
  id: string;
  name: string;
  type: CustomVarType;
  defaultValue: string;
  desc?: string;
}

/* ==================== 类型默认值 ==================== */
function defaultForType(t: CustomVarType): string {
  switch (t) {
    case 'bool': return 'false';
    case 'int': return '0';
    case 'float': return '0.0';
    case 'string': return '""';
    case 'vector': return '0,0,0';
    case 'rotator': return '0,0,0';
    default: return '0';
  }
}

