/* ==================== 可编辑标签名 ==================== */
function EditableTabName({ name, onRename }: { name: string; onRename: (n: string) => void }) {
  const [editing, setEditing] = useState(false);
  const [draft, setDraft] = useState(name);
  useEffect(() => { if (!editing) setDraft(name); }, [name, editing]);
  const commit = () => {
    setEditing(false);
    const t = draft.trim();
    if (t && t !== name) onRename(t);
  };
  if (editing) {
    return (
      <input autoFocus value={draft}
        onChange={(e) => setDraft(e.target.value)}
        onBlur={commit}
        onKeyDown={(e) => {
          if (e.key === 'Enter') commit();
          if (e.key === 'Escape') { setEditing(false); setDraft(name); }
        }}
        onClick={(e) => e.stopPropagation()}
        className="w-24 bg-transparent text-[10px] text-[#e8e6e2] focus:outline-none" />
    );
  }
  return (
    <span onDoubleClick={(e) => { e.stopPropagation(); setEditing(true); }}>{name}</span>
  );
}

