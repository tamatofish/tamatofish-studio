function generateCpp(
  placed: PlacedNode[],
  connections: Connection[],
  customVars: CustomVariable[]
): { header: string; cpp: string } {
  const className = 'AMagicGeneratedActor';
  const lines: string[] = [];
  const hdr: string[] = [];

  hdr.push('// Generated by MAGIC SE Blueprint Editor');
  hdr.push('// Auto-generated C++ from blueprint. Do not edit by hand.');
  hdr.push('');
  hdr.push('#pragma once');
  hdr.push('');
  hdr.push('#include "CoreMinimal.h"');
  hdr.push('#include "GameFramework/Actor.h"');
  hdr.push(`#include "${className}.generated.h"`);
  hdr.push('');
  hdr.push('UCLASS(BlueprintType)');
  hdr.push(`class ${className} : public AActor`);
  hdr.push('{');
  hdr.push('    GENERATED_BODY()');
  hdr.push('');
  hdr.push('public:');
  hdr.push(`    ${className}();`);
  hdr.push('');

  if (customVars.length > 0) {
    hdr.push('    // ---- 变量 ----');
    customVars.forEach((v) => {
      const cppType = {
        float: 'float', int: 'int32', string: 'FString',
        bool: 'bool', vector: 'FVector', rotator: 'FRotator',
      }[v.type];
      hdr.push(`    UPROPERTY(EditAnywhere, BlueprintReadWrite, Category="Magic Vars")`);
      hdr.push(`    ${cppType} ${v.name}${v.defaultValue ? ` = ${v.defaultValue}` : ''};`);
    });
    hdr.push('');
  }

  hdr.push('    // ---- 蓝图逻辑入口 ----');
  hdr.push('    UFUNCTION(BlueprintCallable, Category="Magic Logic")');
  hdr.push('    void RunBlueprint();');
  hdr.push('};');

  lines.push(`#include "${className}.h"`);
  lines.push('');
  lines.push(`${className}::${className}()`);
  lines.push('{');
  lines.push('    PrimaryActorTick.bCanEverTick = false;');
  lines.push('}');
  lines.push('');
  lines.push(`void ${className}::RunBlueprint()`);
  lines.push('{');
  lines.push('    // ---- 由 MAGIC SE 自动生成的蓝图逻辑 ----');
  lines.push('');

  const visited = new Set<string>();
  const ordered: PlacedNode[] = [];
  const visit = (id: string) => {
    if (visited.has(id)) return;
    visited.add(id);
    connections.filter((c) => c.toInstance === id).forEach((c) => visit(c.fromInstance));
    const n = placed.find((x) => x.instanceId === id);
    if (n) ordered.push(n);
  };
  placed.filter((n) => n.category === '事件').forEach((n) => visit(n.instanceId));
  placed.forEach((n) => visit(n.instanceId));

  ordered.forEach((n, idx) => {
    const safe = n.title.replace(/[^a-zA-Z0-9_]/g, '_');
    lines.push(`    // [${idx}] ${n.title} (${n.category})`);
    lines.push(`    {`);
    lines.push(`        // ${n.desc.slice(0, 80)}`);
    lines.push(`        // TODO: 在此补全 ${safe} 的实际调用`);
    if (n.defaultValues) {
      Object.entries(n.defaultValues).forEach(([k, v]) => {
        lines.push(`        // 参数[${k}] = ${v}`);
      });
    }
    lines.push(`    }`);
    lines.push('');
  });

  lines.push('}');
  return { header: hdr.join('\n'), cpp: lines.join('\n') };
}

/* ==================== 粒子背景 ==================== */
function ParticleBackground() {
  const canvasRef = useRef<HTMLCanvasElement>(null);
  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    if (!ctx) return;
    let w = (canvas.width = window.innerWidth);
    let h = (canvas.height = window.innerHeight);
    const particles: { x: number; y: number; vx: number; vy: number; r: number; a: number; c: string }[] = [];
    for (let i = 0; i < 55; i++) {
      particles.push({
        x: Math.random() * w, y: Math.random() * h,
        vx: (Math.random() - 0.5) * 0.18, vy: (Math.random() - 0.5) * 0.18,
        r: Math.random() * 1.4 + 0.3, a: Math.random() * 0.35 + 0.08,
        c: Math.random() < 0.6 ? GOLD : MINT,
      });
    }
    const onResize = () => { w = canvas.width = window.innerWidth; h = canvas.height = window.innerHeight; };
    window.addEventListener('resize', onResize);
    let raf = 0;
    const draw = () => {
      ctx.clearRect(0, 0, w, h);
      for (const p of particles) {
        p.x += p.vx; p.y += p.vy;
        if (p.x < -10) p.x = w + 10; if (p.x > w + 10) p.x = -10;
        if (p.y < -10) p.y = h + 10; if (p.y > h + 10) p.y = -10;
        ctx.beginPath();
        ctx.arc(p.x, p.y, p.r, 0, Math.PI * 2);
        ctx.fillStyle = p.c === GOLD ? `rgba(200,169,106,${p.a})` : `rgba(107,168,154,${p.a})`;
        ctx.fill();
      }
      for (let i = 0; i < particles.length; i++) {
        for (let j = i + 1; j < particles.length; j++) {
          const dx = particles[i].x - particles[j].x;
          const dy = particles[i].y - particles[j].y;
          const dist = Math.sqrt(dx * dx + dy * dy);
          if (dist < 130) {
            ctx.beginPath();
            ctx.moveTo(particles[i].x, particles[i].y);
            ctx.lineTo(particles[j].x, particles[j].y);
            ctx.strokeStyle = `rgba(200,169,106,${(1 - dist / 130) * 0.05})`;
            ctx.lineWidth = 0.5;
            ctx.stroke();
          }
        }
      }
      raf = requestAnimationFrame(draw);
    };
    draw();
    return () => { cancelAnimationFrame(raf); window.removeEventListener('resize', onResize); };
  }, []);
  return <canvas ref={canvasRef} className="pointer-events-none fixed inset-0 z-0" aria-hidden="true" />;
}

