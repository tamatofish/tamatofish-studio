function Tour({ step, targetRef, onNext, onPrev, onSkip, isLast }: {
  step: TourStep; targetRef: React.RefObject<HTMLElement | null>;
  onNext: () => void; onPrev: () => void; onSkip: () => void; isLast: boolean;
}) {
  const [rect, setRect] = useState<DOMRect | null>(null);
  const [mounted, setMounted] = useState(false);
  useEffect(() => { setMounted(true); }, []);
  useEffect(() => {
    const update = () => {
      const el = targetRef.current;
      if (!el) { setRect(null); return; }
      const r = el.getBoundingClientRect();
      if (r.width < 2 || r.height < 2) { setRect(null); return; }
      setRect(r);
    };
    update();
    const id = window.setInterval(update, 300);
    window.addEventListener('resize', update);
    window.addEventListener('scroll', update, true);
    return () => {
      window.clearInterval(id);
      window.removeEventListener('resize', update);
      window.removeEventListener('scroll', update, true);
    };
  }, [targetRef]);

  if (!mounted) return null;
  if (!rect) {
    return createPortal(
      <div className="pointer-events-none fixed inset-0 z-[300]">
        <div className="pointer-events-auto absolute inset-0 bg-black/70 backdrop-blur-sm" />
        <div className="pointer-events-auto absolute left-1/2 top-1/2 w-[380px] -translate-x-1/2 -translate-y-1/2 border shadow-2xl backdrop-blur-xl"
          style={{ borderColor: 'rgba(232,230,226,0.08)', background: '#1b1b1e' }}>
          <TourCard step={step} onNext={onNext} onPrev={onPrev} onSkip={onSkip} isLast={isLast} />
        </div>
      </div>,
      document.body
    );
  }
  const PAD = 8;
  const left = Math.max(0, rect.left - PAD);
  const top = Math.max(0, rect.top - PAD);
  const right = Math.min(window.innerWidth, rect.right + PAD);
  const bottom = Math.min(window.innerHeight, rect.bottom + PAD);
  const boxW = right - left, boxH = bottom - top;
  const CARD_W = 360, CARD_H = 220, GAP = 16;
  const placement = step.placement ?? 'right';
  let cardLeft = 0, cardTop = 0;
  const tryPlace = (p: 'right' | 'left' | 'bottom' | 'top') => {
    switch (p) {
      case 'right': cardLeft = right + GAP; cardTop = top; break;
      case 'left': cardLeft = left - CARD_W - GAP; cardTop = top; break;
      case 'bottom': cardLeft = left; cardTop = bottom + GAP; break;
      case 'top': cardLeft = left; cardTop = top - CARD_H - GAP; break;
    }
  };
  tryPlace(placement);
  const fits = (p: 'right' | 'left' | 'bottom' | 'top') => {
    let cl = 0, ct = 0;
    switch (p) {
      case 'right': cl = right + GAP; ct = top; break;
      case 'left': cl = left - CARD_W - GAP; ct = top; break;
      case 'bottom': cl = left; ct = bottom + GAP; break;
      case 'top': cl = left; ct = top - CARD_H - GAP; break;
    }
    return cl >= 8 && ct >= 8 && cl + CARD_W <= window.innerWidth - 8 && ct + CARD_H <= window.innerHeight - 8;
  };
  if (!fits(placement)) {
    const fallbacks: Array<'right' | 'left' | 'bottom' | 'top'> = ['right', 'left', 'bottom', 'top'];
    const alt = fallbacks.find((p) => p !== placement && fits(p));
    if (alt) tryPlace(alt);
    else { cardLeft = window.innerWidth / 2 - CARD_W / 2; cardTop = window.innerHeight / 2 - CARD_H / 2; }
  }
  cardLeft = Math.max(8, Math.min(window.innerWidth - CARD_W - 8, cardLeft));
  cardTop = Math.max(8, Math.min(window.innerHeight - CARD_H - 8, cardTop));
  const tourNode = (
    <div className="pointer-events-none fixed inset-0 z-[300]">
      <div className="pointer-events-auto absolute bg-black/60" style={{ left: 0, top: 0, right: 0, height: top }} />
      <div className="pointer-events-auto absolute bg-black/60" style={{ left: 0, bottom: 0, right: 0, top: bottom }} />
      <div className="pointer-events-auto absolute bg-black/60" style={{ left: 0, top, width: left, height: boxH }} />
      <div className="pointer-events-auto absolute bg-black/60" style={{ right: 0, top, left: right, height: boxH }} />
      <div className="pointer-events-none absolute border"
        style={{ left, top, width: boxW, height: boxH, borderColor: GOLD, boxShadow: `0 0 0 1px ${GOLD_SOFT}` }} />
      <div className="pointer-events-auto absolute border shadow-2xl backdrop-blur-xl"
        style={{ left: cardLeft, top: cardTop, width: CARD_W, borderColor: 'rgba(232,230,226,0.08)', background: '#1b1b1e' }}>
        <TourCard step={step} onNext={onNext} onPrev={onPrev} onSkip={onSkip} isLast={isLast} />
      </div>
    </div>
  );
  return createPortal(tourNode, document.body);
}

/* ==================== 磨砂面板 ==================== */
function DraggablePanel({ title, initial, children, onMinimize, onClose, zIndex, onFocus }: {
  title: string; initial: { x: number; y: number }; children: React.ReactNode;
  onMinimize?: () => void; onClose?: () => void; zIndex: number; onFocus: () => void;
}) {
  const [pos, setPos] = useState(initial);
  const dragRef = useRef<{ active: boolean; dx: number; dy: number } | null>(null);
  const onDown = (e: React.MouseEvent) => { dragRef.current = { active: true, dx: e.clientX - pos.x, dy: e.clientY - pos.y }; };
  useEffect(() => {
    const onMove = (e: MouseEvent) => {
      const d = dragRef.current;
      if (!d?.active) return;
      setPos({ x: Math.max(0, Math.min(window.innerWidth - 200, e.clientX - d.dx)), y: Math.max(0, Math.min(window.innerHeight - 40, e.clientY - d.dy)) });
    };
    const onUp = () => { if (dragRef.current) dragRef.current.active = false; };
    window.addEventListener('mousemove', onMove); window.addEventListener('mouseup', onUp);
    return () => { window.removeEventListener('mousemove', onMove); window.removeEventListener('mouseup', onUp); };
  }, []);
  return (
    <div className="fixed overflow-hidden border shadow-[0_8px_32px_rgba(0,0,0,0.5)] backdrop-blur-xl"
      style={{ left: pos.x, top: pos.y, minWidth: 280, zIndex, borderRadius: 2, borderColor: 'rgba(232,230,226,0.08)', background: '#1b1b1e' }}
      onMouseDown={onFocus}>
      <div className="pointer-events-none absolute inset-x-0 top-0 h-px"
        style={{ background: `linear-gradient(to right, transparent, ${GOLD_SOFT}, transparent)` }} />
      <div onMouseDown={onDown} className="flex cursor-move select-none items-center justify-between border-b px-3 py-2"
        style={{ borderColor: 'rgba(232,230,226,0.06)', background: 'rgba(255,255,255,0.015)' }}>
        <p className="text-xs font-normal tracking-[0.1em] text-[#e8e6e2]">{title}</p>
        <div className="flex items-center gap-2">
          {onMinimize && (
            <button type="button" onClick={onMinimize} className="grid h-4 w-4 place-items-center text-[#5b5852] transition-colors hover:text-[#e8e6e2]">
              <span className="h-3 w-3">{Icon.minimize}</span>
            </button>
          )}
          {onClose && (
            <button type="button" onClick={onClose} className="grid h-4 w-4 place-items-center text-[#5b5852] transition-colors hover:text-[#e8e6e2]">
              <span className="h-3 w-3">{Icon.close}</span>
            </button>
          )}
        </div>
      </div>
      {children}
    </div>
  );
}
